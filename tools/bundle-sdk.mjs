#!/usr/bin/env node
// Restricted first-party bundler: deterministic closed module graph, no dependencies.
import {readFile, writeFile} from 'node:fs/promises';
import {dirname, resolve, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), entry = 'src/sdk/Ferrite.js';
const seen = new Map(), active = new Set(), ordered = [];
async function visit(path) {
  if (seen.has(path)) return;
  if (active.has(path)) throw Error('SDK dependency cycle: ' + path);
  active.add(path);
  const original = await readFile(resolve(root, path), 'utf8'); let source = original;
  const imports = [];
  for (const match of source.matchAll(/^import\s*\{([^}]+)\}\s*from\s*(['"])([^'"]+)\2;?\s*$/gm)) {
    if (!match[3].startsWith('.')) throw Error('SDK may import only first-party modules');
    const dependency = relative(root, resolve(root, dirname(path), match[3])).replaceAll('\\', '/');
    if (!dependency.startsWith('src/')) throw Error('SDK import escaped src/');
    await visit(dependency); imports.push({match: match[0], names: match[1].trim(), dependency});
  }
  for (const item of imports) source = source.replace(item.match, `const {${item.names.replace(/\s+as\s+/g, ': ')}} = __modules[${JSON.stringify(item.dependency)}];`);
  const exports = [];
  source = source.replace(/^export\s+(class|function|const|let|var)\s+(\w+)/gm, (_, kind, name) => { exports.push(name); return `${kind} ${name}`; });
  source = source.replace(/^export\s*\{([^}]+)\};?\s*$/gm, (_, names) => { for (const name of names.split(',').map(value => value.trim())) { if (!/^\w+$/.test(name)) throw Error('Unsupported SDK re-export'); exports.push(name); } return ''; });
  if (/^\s*(?:import|export)\s/m.test(source) || /import\.meta/.test(source)) throw Error('Unsupported SDK module syntax: ' + path);
  active.delete(path); seen.set(path, createHash('sha256').update(original).digest('hex'));
  ordered.push(`// ${path}\n__modules[${JSON.stringify(path)}] = (() => {\n${source}\nreturn {${[...new Set(exports)].join(',')}};\n})();`);
}
await visit(entry);
const fingerprint = createHash('sha256').update(JSON.stringify([...seen])).digest('hex');
const output = `// GENERATED by tools/bundle-sdk.mjs. Do not edit.\n// Source fingerprint: ${fingerprint}\n'use strict';\n(() => {\nconst __modules = Object.create(null);\n${ordered.join('\n\n')}\nObject.defineProperty(globalThis, 'Ferrite', {value: __modules[${JSON.stringify(entry)}].Ferrite, configurable: true});\n})();\n`;
const path = resolve(root, 'src/sdk/ferrite.bundle.js');
if (process.argv.includes('--check')) { if (await readFile(path, 'utf8') !== output) throw Error('Outdated SDK bundle'); } else await writeFile(path, output);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Bundled'} Ferrite SDK: ${seen.size} modules, ${output.length} characters`);
