#!/usr/bin/env node
// Deterministic first-party worker packer. This is not a general JavaScript bundler.
// Sources remain one-class-per-file; checked generated bundles avoid worker import waterfalls.
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const entries=['src/ui/workers/compile-worker.js','src/ui/workers/execution-worker.js'];
for(const entry of entries){
  const seen=new Map(),active=new Set(),ordered=[];
  async function visit(path){
    if(seen.has(path))return;if(active.has(path))throw Error(`Worker dependency cycle at ${path}`);active.add(path);
    let source=await readFile(resolve(root,path),'utf8');const original=source;const imports=[];
    const pattern=/^import\s*\{([^}]+)\}\s*from\s*(['"])([^'"]+)\2;?\s*$/gm;
    for(const match of source.matchAll(pattern)){
      if(!match[3].startsWith('.'))throw Error('Worker bundle may only import project modules');
      const dependency=relative(root,resolve(root,dirname(path),match[3])).replaceAll('\\','/');
      if(!dependency.startsWith('src/'))throw Error('Worker import escaped src/');
      await visit(dependency);imports.push({match:match[0],names:match[1].trim(),dependency});
    }
    for(const item of imports)source=source.replace(item.match,`const {${item.names.replace(/\s+as\s+/g,': ')}} = __modules[${JSON.stringify(item.dependency)}];`);
    const exports=[];
    source=source.replace(/^export\s+(class|function|const|let|var)\s+(\w+)/gm,(_,kind,name)=>{exports.push(name);return `${kind} ${name}`;});
    source=source.replace(/^export\s*\{([^}]+)\};?\s*$/gm,(_,names)=>{for(const name of names.split(',').map(x=>x.trim())){if(!/^\w+$/.test(name))throw Error('Unsupported re-export');exports.push(name);}return '';});
    if(/^\s*(?:import|export)\s/m.test(source)||/import\.meta/.test(source))throw Error(`Unsupported worker module syntax: ${path}`);
    active.delete(path);seen.set(path,createHash('sha256').update(original).digest('hex'));
    ordered.push(`// ${path}\n__modules[${JSON.stringify(path)}] = (() => {\n${source}\nreturn {${exports.join(',')}};\n})();`);
  }
  await visit(entry);
  const fingerprint=createHash('sha256').update(JSON.stringify([...seen])).digest('hex');
  const output=`// GENERATED by tools/bundle-workers.mjs. Do not edit.\n// Source fingerprint: ${fingerprint}\n'use strict';\n(() => {\nconst __modules = Object.create(null);\n${ordered.join('\n\n')}\n})();\n`;
  const target=resolve(root,entry.replace(/\.js$/,'.bundle.js'));
  if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==output)throw Error(`Outdated worker bundle: ${relative(root,target)}`);}
  else await writeFile(target,output);
  console.log(`${process.argv.includes('--check')?'Verified':'Bundled'} ${entry}: ${seen.size} modules, ${output.length} characters`);
}
